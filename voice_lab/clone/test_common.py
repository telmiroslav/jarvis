"""Быстрые проверки нормализации русского текста: python3 test_common.py (нужен num2words)."""
from common import normalize_ru, split_sentences

CASES = {
    "Температура в комнате 22 градуса.": "Температура в комнате двадцать два градуса.",
    "Напоминаю: в 19:00 у вас звонок.": "Напоминаю: в девятнадцать ноль-ноль у вас звонок.",
    "В 7:05 и в 19:30.": "В семь ноль пять и в девятнадцать тридцать.",
    "Громкость 30%.": "Громкость тридцать процентов.",
    "Осталось 21 минуту, 1 процент, 31 секунда.": "Осталось двадцать одну минуту, один процент, тридцать одна секунда.",
    "На улице -5°C.": "На улице минус пять градусов Цельсия.",
    "Но если вы настаиваете — выполняю.": "Но если вы настаиваете, выполняю.",
    "Всего 1 200 штук.": "Всего одна тысяча двести штук.",
}

if __name__ == "__main__":
    bad = 0
    for src, want in CASES.items():
        got = normalize_ru(src)
        ok = got == want
        bad += not ok
        print(("ok  " if ok else "FAIL"), src, "->", got, "" if ok else f"(ожидалось: {want})")
    assert split_sentences("Готово. Музыка включена, громкость тридцать процентов.") == [
        "Готово.", "Музыка включена, громкость тридцать процентов."]
    raise SystemExit(1 if bad else 0)
