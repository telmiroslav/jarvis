#pragma once

// Кольцо отсчётов PCM16 для звука микрофона, который ещё не ушёл серверу (mic_stream.cc). Чистая логика без ESP-IDF и без блокировок
// (проверяется на обычном компьютере, firmware/test_host); замок вокруг неё держит mic_stream.cc.
//
// Главное правило v0.5.1: когда кольцо переполнено (сеть встала дольше, чем кольцо вмещает), выбрасывается САМЫЙ СТАРЫЙ звук, а не
// новый. Раньше терялся новый: в середине фразы появлялась дыра, а после неё шёл звук с отставанием в целое кольцо. Теперь сервер
// получает ровный кусок «последние N секунд», а дыра приходится на начало (сервер в любом случае видит фразу с её хвоста).

#include <stddef.h>
#include <stdint.h>

namespace jarvis {

class SampleRing {
public:
    // storage живёт, пока живо кольцо; capacity в отсчётах
    void init(int16_t *storage, size_t capacity);

    // Всё выброшено (счётчик отброшенного остаётся)
    void clear();

    // Кладёт n отсчётов. Не хватает места: старые отсчёты отбрасываются (если n больше всего кольца, остаётся только последний его
    // кусок). Возвращает, сколько отсчётов отброшено (старых или, если n > capacity, лишних из начала n).
    size_t push_drop_oldest(const int16_t *pcm, size_t n);

    // Копирует до max самых старых отсчётов в dst, не забирая их. Возвращает, сколько скопировано. mark (если задан) запоминает
    // состояние кольца для consume_peeked(): между peek и успешной отправкой звук с микрофона мог вытеснить самые старые отсчёты.
    size_t peek(int16_t *dst, size_t max, uint64_t *mark = nullptr) const;
    // Забирает n самых старых отсчётов (не больше, чем есть)
    void consume(size_t n);
    // Забирает то, что было отдано peek() (n отсчётов, mark оттуда же), с поправкой на вытеснение: отсчёты, которые за это время
    // выбросило переполнение, уже не в кольце и повторно не забираются (иначе пропали бы ещё не отправленные новые). После clear() ничего.
    void consume_peeked(size_t n, uint64_t mark);
    // peek + consume
    size_t pop(int16_t *dst, size_t max);

    size_t size() const { return count_; }
    size_t capacity() const { return cap_; }
    uint64_t dropped_total() const { return dropped_; }

private:
    int16_t *buf_ = nullptr;
    size_t cap_ = 0;
    size_t head_ = 0;
    size_t count_ = 0;
    uint64_t dropped_ = 0;
    uint32_t epoch_ = 0;       // растёт при каждом clear()
};

}  // namespace jarvis
