#pragma once

// Движок слова microWakeWord на плате: встроенная модель «Джарвис» (main/models/jarvis_ru.tflite + .json), признаки и нейросеть
// из mww_core.cc, решения (скользящее среднее, порог, пауза, «почти слово») из mww_logic.cc. Здесь только то, что привязано к ESP-IDF:
// встроенные файлы, память (PSRAM), задача и измерения. wake.cc выбирает движок, отдаёт сюда звук и забирает слово.
//
// Где что считается. Отдельная задача «mww» на ядре 0 с приоритетом 1 (как wake_fetch: Wi-Fi, звук и связь вытесняют её, главный
// цикл делит ядро с ней по кругу). Ядро 1 занято LVGL (при записи он забирает почти всё ядро), там слову не досталось бы
// процессора. Задача закреплена за ядром 0 ещё и потому, что считает на FPU (задача с FPU на ESP32-S3 всё равно привязывается
// к ядру). Арена тензоров (около 34 КБ), копия модели (61 КБ), состояние признаков и объект ядра лежат в PSRAM; во внутренней
// памяти только стек задачи (5 КБ).
//
// Звук. Задача сама читает кольцо «для движка» (wake.cc) со своей позиции и применяет то же усиление, что и AFE (wake gain, а пока
// звучит ответ при включённом перебивании звук в кольце уже ослаблен на 12 дБ, и усиление не применяется). Для AFE кольцо читает
// feed_task, они друг другу не мешают. Положение слова для окна записи (то, что у ESP-SR называлось afe_pos) это позиция
// последнего отсчёта, который прошёл через модель к моменту решения: всё, что до неё, относится к слову.

#include <stddef.h>
#include <stdint.h>

#include "wake_perf.h"

namespace jarvis {
namespace mww {

struct Hit {
    int64_t pos = 0;             // индекс отсчёта (как у кольца wake.cc), до которого дошла модель: всё до него относится к слову
    int64_t edge = 0;            // сколько отсчётов принято в кольцо к этому моменту
    double avg = 0.0;            // среднее окна вероятностей
    double peak = 0.0;           // самая большая вероятность в окне
};

// Что движку дают из wake.cc. Все функции быстрые; read и hit берут замок wake.cc сами.
struct Source {
    // Копирует следующие отсчёты кольца для движка, начиная с индекса *pos, в dst (не больше max), сдвигает *pos. Возвращает, сколько
    // отсчётов скопировано (0: нового пока нет). Если движок отстал больше чем на кольцо, сам прыгает к живому звуку и ставит *skipped.
    size_t (*read)(int64_t *pos, int16_t *dst, size_t max, bool *skipped) = nullptr;
    float (*gain)() = nullptr;         // усиление звука для движка сейчас (wake gain; 1.0, пока звучит ответ)
    bool (*running)() = nullptr;       // слово включено (wake on); при wake off звук в кольцо не идёт
    int64_t (*edge)() = nullptr;       // сколько отсчётов принято в кольцо всего
    void (*hit)(const Hit &h) = nullptr;   // слово услышано (зовётся из задачи mww)
};

// Готовит движок: манифест, модель в PSRAM, ядро (арена, признаки), задача (пока ждёт go()). false: причина в why (строка
// без пробелов для лога и для команды wake) и в логе подробности. Память освобождена, повторный вызов допустим.
bool prepare(const Source &src, char *why, size_t why_cap);
// AFE поднят, задача может работать
void go();
// Остановить задачу и освободить память (запасной путь, когда без mww не обойтись или AFE не поднялся)
void shutdown();
bool ready();
// Есть новый звук (из sink())
void notify();

// Порог срабатывания сейчас (то, что видит детектор на следующей вероятности). Задаёт wake.cc: обычный или строже на время ответа.
void set_cutoff(double c);
double cutoff();
double default_cutoff();               // из манифеста (0,90)

struct Snapshot {
    bool ready = false;
    char wake_word[48] = {0};
    char model[48] = {0};
    int window = 0;
    double cutoff = 0.0;
    double default_cutoff = 0.0;
    uint32_t detections = 0;
    uint32_t suppressed = 0;           // порог превышен, но в паузе после слова или в прогреве
    uint32_t near_misses = 0;
    bool have_last_peak = false;
    double last_peak = 0.0;            // вершина последнего всплеска выше 0,60
    double avg_now = 0.0;
    uint32_t overruns = 0;             // сколько раз задача отстала на целое кольцо и пропустила звук
    uint32_t step_errors = 0;
    uint32_t stack_free_bytes = 0;
    size_t model_bytes = 0;
    size_t arena_bytes = 0;
    size_t arena_used = 0;
    size_t object_bytes = 0;
    int arena_attempts = 0;
};
Snapshot snapshot();

// Измерения (то же устройство, что у wake_perf для AFE): за период WAKE stat (забирается), за запись по слову и за всё время
wake_perf::MwwAcc acc_take_period();
void acc_rec_begin();
wake_perf::MwwAcc acc_rec();
wake_perf::MwwAcc acc_total();

}  // namespace mww
}  // namespace jarvis
