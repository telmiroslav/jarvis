#pragma once

// Арифметика над 32-битными миллисекундами (esp_timer / 1000, переполнение через 49,7 суток). Без ESP-IDF.
//
// Зачем это нужно. Метки времени берут разные задачи: главный цикл берёт «сейчас» в начале прохода и потом несколько мс
// (а под нагрузкой десятки и сотни) делает другие дела, а сетевая задача за это время успевает принять сообщение и записать
// в автомат свою, более позднюю метку. Если потом посчитать «now - t» беззнаково, а t оказалась после now, получится
// около 4 миллиардов: любое «прошло дольше N мс» срабатывает сразу. В v0.4.0 так обрывался ответ после первого слова:
// Dialog::on_tick() увидел «звук не приходил 49 суток» и выключил динамик. Поэтому прошедшее время всегда считаем через
// elapsed(): метка из будущего даёт 0, а не огромное число.

#include <stdint.h>

namespace jarvis {
namespace timeutil {

// now достигло t (или прошло его). Знаковое сравнение: верно и через переполнение счётчика, пока обе метки в пределах
// 24 суток друг от друга.
inline bool reached(uint32_t now, uint32_t t) { return static_cast<int32_t>(now - t) >= 0; }

// Сколько мс прошло от t до now. Если t позже now (метку поставила другая задача, уже после того, как now было взято),
// возвращает 0. Метка старше 24 суток тоже даёт 0 (знаковая арифметика): для тайм-аутов в секунды это не бывает.
inline uint32_t elapsed(uint32_t now, uint32_t t)
{
    const int32_t d = static_cast<int32_t>(now - t);
    return d > 0 ? static_cast<uint32_t>(d) : 0u;
}

}  // namespace timeutil
}  // namespace jarvis
