#pragma once

// Интерфейс на экране 240x240: строка состояния (Wi-Fi, часы), лицо, субтитры.
// Написан на LVGL 9 и не знает про ESP-IDF, поэтому та же самая картинка рисуется на обычном компьютере
// (firmware/test_host, картинки в test_host/renders). На плате его запускает gui.cc.
//
// Потоки. Все функции set_*, clear_texts и state() можно вызывать из любой задачи в любой момент:
// они только кладут значение в общую модель под мьютексом, а рисует и анимирует таймер LVGL
// (каждые ~30 мс), никаких блокировок LVGL снаружи не нужно. Только init() вызывается один раз
// из задачи, которая держит замок LVGL (или до запуска задачи LVGL).
//
// Раскладка (240x240):
//     0..22   строка состояния: значок Wi-Fi слева, часы справа
//    22..148  лицо (без субтитров занимает весь экран, с субтитрами уезжает вверх и уменьшается)
//   151..168  строка «Вы: ...» (мелко, серым), когда внизу идёт ответ
//   171..237  субтитры: ровно 3 строки на виду, длинное само плавно прокручивается за чтением

#include <stddef.h>
#include <stdint.h>

#include "lvgl.h"

namespace jarvis {
namespace ui {

constexpr int kWidth = 240;
constexpr int kHeight = 240;

// Предел длины текста субтитров в байтах (длиннее обрезается по границе символа)
constexpr size_t kMaxTextBytes = 600;

enum class State : uint8_t {
    Idle = 0,    // ждёт: моргает, иногда косится
    Listening,   // слушает: глаза шире, вокруг живёт свечение и полоски по уровню микрофона
    Thinking,    // думает: смотрит вверх в сторону, бегут три точки
    Speaking,    // говорит: глаза «дышат» в такт звуку динамика, под ними полоски-волна
    NoWifi,      // нет Wi-Fi: сонный взгляд
    NoServer,    // Wi-Fi есть, а сервера на ноутбуке нет: тот же сонный взгляд, внизу подсказка
    Error,       // ошибка: сонный взгляд тёплого цвета
    Sleep,       // спит: глаза закрыты, тускло
    Follow,      // окно «договорить без слова» после ответа: слушает спокойно (глаза чуть шире обычных, свечение тише, без полосок)
};
const char *state_name(State s);

enum class WifiIcon : uint8_t {
    Off = 0,      // перечёркнутый значок (сети нет или не настроена)
    Connecting,   // деления по очереди загораются
    Connected,    // горят bars делений из трёх
};

// Создаёт все объекты на активном экране disp. seed нужен случайным морганиям.
void init(lv_display_t *disp, uint32_t seed = 1);

// ---- потокобезопасные функции модели

void set_state(State s);
State state();

// Уровни звука 0..1 (значения за пределами обрезаются). Лицо само сглаживает их между вызовами.
void set_mic_level(float level);   // что слышит микрофон (для Listening)
void set_out_level(float level);   // что играет динамик (для Speaking)

void set_wifi(WifiIcon icon, int bars);
void set_clock(int hour, int minute);
void clear_clock();                // показывает «--:--»

// Субтитры. Текст в UTF-8, символы вне шрифта заменяются на «?». Растущий текст (прежний + продолжение)
// не сбрасывает прокрутку. Пустая строка убирает текст.
void set_user_text(const char *utf8);     // «Вы: ...», приглушённо
void set_jarvis_text(const char *utf8);   // ответ, ярко; длинный сам прокручивается за чтением
void set_hint(const char *utf8);          // подсказка системы (например про Wi-Fi), тёплым цветом, самая слабая
void clear_texts();                       // и «Вы», и ответ (подсказка остаётся)

// Сколько кадров LVGL реально отрисовал с момента загрузки (для строки STATUS в логе)
uint32_t frames();

// Только для тестов и отладки на компьютере
namespace testing {
void blink_now();                  // начать моргание немедленно (и снять паузу ниже)
void pause_motion(bool pause);     // true: не запускать случайные моргания и взгляды (картинки без случайности)
int32_t scroll_px();               // на сколько пикселей прокручен текст субтитров
int main_text_height();            // полная высота текста субтитров
int main_view_height();            // высота окна субтитров
}  // namespace testing

}  // namespace ui
}  // namespace jarvis
