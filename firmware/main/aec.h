#pragma once

// Эхоподавление для распознавания слова (v0.6.0): плата знает, что сама играет, и вычитает это из микрофона, чтобы «Джарвис» было слышно поверх своей музыки
// (и поверх своего голоса, когда он перебивается). Работает ТОЛЬКО на пути к движку слова: на сервер звук микрофона уходит как был.
//
// Что это за часть. aec_logic.h: вся арифметика без железа (ресемплер 24 -> 16 кГц, кольца, выравнивание по времени, измерение ослабления, измерение
// задержки, синтетика), проверена на компьютере. Здесь только железо: AEC из ESP-SR 2.6.1 (esp_aec.h: aec_create_from_config / aec_process, без AFE, как
// отдельная библиотека), задача, связь с динамиком (AudioOut::set_ref_tap) и со словом (wake.cc).
//
// ESP-SR AEC (проверено по заголовкам и библиотеке из managed_components, цифры из документации Espressif и таблицы ресурсов):
//   - 16 кГц, один микрофон, один опорный канал; кадр aec_get_chunksize() = 512 отсчётов (32 мс) для режимов SR и FD; filter_length = число «блоков» фильтра,
//     рекомендация 4 (больше дольше хвост эха и больше процессора);
//   - режимы: SR_LOW_COST и SR_HIGH_PERF (только линейный фильтр, 2,3 и 4,5 мс на кадр по документации), FD_LOW_COST и FD_HIGH_PERF (плюс подавитель остатка NLP, 6,3
//     и 8,1 мс на кадр). По умолчанию FD_LOW_COST (рекомендация Espressif), NLP «normal» (меньше портит речь поверх музыки);
//   - буфера кадров 16-байтовые (heap_caps_aligned_alloc); память инстанса в PSRAM (caps в aec_config_t).
//
// Поток данных. Динамик: задача звука после каждой записи куска в I2S зовёт ref_tap() с тем, что РЕАЛЬНО ушло (после громкости): 480 отсчётов 24 кГц -> 320 отсчётов
// 16 кГц в кольцо опоры, плюс метка времени «запись вернулась» (Aligner::ref_chunk). Микрофон: задача audio_in зовёт note_mic_block() на каждый блок (якорь времени)
// и, пока путь AEC включён, push_mic() (копия блока для движка в очередь). Задача «aec» (ядро 1, приоритет 3: ядро 0 занято Wi-Fi, mww и VAD, а LVGL на ядре 1
// при музыке почти молчит) берёт кадр 512 из очереди, ищет по выравниванию кадр опоры, зовёт aec_process и отдаёт очищенный звук слову (hooks.out).
//
// Бюджет процессора (оценка, измерить: aec bench). Документация Espressif для 240 МГц: FD_LOW_COST около 20% одного ядра (6,3 мс на кадр в 32 мс), SR_LOW_COST около 7%;
// таблица AFE для ESP32-S3 (кадр подачи с AEC) даёт 9..12% ядра. Задача на ядре 1 не трогает ядро 0, где mww+VAD берут 50..65% и ещё Wi-Fi.
//
// Включается только пока динамик играет (музыка; голос Джарвиса, если aec voice on) и ещё 0,6 с после (хвост эха); в остальное время AEC не считает ничего.

#include <stddef.h>
#include <stdint.h>

#include "aec_logic.h"

namespace jarvis {

class AudioOut;

namespace aec {

// Что от слова (wake.cc). Все три зовутся из задачи «aec».
struct Hooks {
    // Очищенный звук для движка слова (уровень уже приведён к обычному): n отсчётов подряд, продолжение уже отданного
    void (*out)(const int16_t *clean, size_t n) = nullptr;
    // Включить путь AEC: с этого момента sink() слова не пишет звук для движка сам, а отдаёт его push_mic(). Под замком слова: внутри вызывается mark_activated().
    bool (*activate)() = nullptr;
    // Выключить путь, если очередь AEC пуста (под замком слова проверяет pending_samples() == 0 и выключает атомарно). true: выключено.
    bool (*try_deactivate)() = nullptr;
};

// Поднимает AEC (память, задача, опорный сигнал от динамика), настройки берёт из NVS. false: недоступен (причина в why(), слово и музыка работают без него).
bool init(AudioOut *out, const Hooks &hooks);
bool available();
const char *why();

// ---- вызывает слово (задача audio_in, под замком слова; быстрые, ничего не ждут)
// Блок микрофона для движка принят (n отсчётов, t_us время прихода): якорь времени. Всегда, даже когда AEC не нужен.
void note_mic_block(size_t n, int64_t t_us);
// Блок положить в очередь AEC (только пока путь включён, сразу после note_mic_block того же блока)
void push_mic(const int16_t *engine_pcm, size_t n);
// Для hooks: сколько отсчётов в очереди AEC ждёт обработки, и «путь только что включён» (с этого номера читать очередь)
size_t pending_samples();
void mark_activated();
void mark_deactivated();   // путь закрыт (зовёт слово в try_deactivate, когда очередь пуста)

// ---- главный цикл (каждые ~10 мс)
// want: динамик сейчас играет и AEC нужен (музыка слышна, или голос и aec voice on). Хвост 0,6 с и включение по готовности выравнивания внутри.
void request(bool want, uint32_t now_ms);
// Во сколько раз поднять выход AEC (вход ослаблен на 12 дБ, пока динамик громкий: 4; без ослабления 1). Берётся со следующего кадра.
void set_makeup(int gain);
// Путь AEC включён (звук для движка идёт через него)
bool path_active();
// Задача «aec» не отдаёт звук, хотя он ждёт (завис, не хватает процессора): слово должно вернуться к прямому пути. now_ms: часы вызывающего.
bool stalled(uint32_t now_ms);
// Забирает до max отсчётов из очереди AEC без обработки (слово возвращается к прямому пути после завала); возвращает число
size_t take_pending_raw(int16_t *dst, size_t max);
void note_stall_recovery();

// ---- настройки (сохраняются в NVS; действуют сразу, кроме mode/taps/nlp: они пересоздают AEC, когда он не считает). false: значение вне пределов или не записалось.
aec_logic::Config config();
bool set_enabled(bool on);
bool set_voice(bool on);
bool set_delay_ms(int ms);
bool set_taps(int taps);
bool set_mode(aec_logic::Mode m);
bool set_nlp(int level);

// ---- диагностика
struct Status {
    bool available = false;
    const char *why = "";
    bool enabled = false;
    bool active = false;                    // путь AEC включён сейчас
    bool want = false;                      // динамик играет, AEC нужен (с хвостом)
    aec_logic::Config cfg;
    int frame = 0;                          // отсчётов в кадре AEC (512)
    uint32_t activations = 0;
    uint32_t frames = 0;                    // кадров обработано AEC
    uint32_t skipped = 0;                   // кадров пропущено: AEC отстал больше чем на 0,5 с (звук прошёл как есть)
    uint32_t proc_avg_us = 0;               // время aec_process на кадр
    uint32_t proc_max_us = 0;
    float cpu_pct = 0.0f;                   // доля одного ядра: proc_avg / 32 мс
    float erle_db = 0.0f;                   // ослабление эха за текущее включение (энергия до / после на кадрах со звучащей опорой)
    float erle_win_db = 0.0f;               // и за окно с прошлой строки в логе
    float mic_dbfs = -120.0f;               // уровень входа и выхода AEC, опоры (по кадрам со звучащей опорой, за текущее включение)
    float out_dbfs = -120.0f;
    float ref_dbfs = -120.0f;
    uint32_t erle_frames = 0;
    bool aligned = false;                   // выравнивание готово
    int64_t anchor_diff_us = 0;
    uint32_t align_jumps = 0;
    uint32_t streams = 0;                   // потоков динамика замечено
    int makeup = 1;
    uint32_t pending = 0;                   // отсчётов ждёт в очереди
    uint32_t stall_recoveries = 0;
    uint32_t stack_free_bytes = 0;
    uint32_t internal_used_bytes = 0;       // сколько внутренней памяти взял AEC при создании (по разности свободной памяти)
    uint32_t psram_used_bytes = 0;
    char lib[96] = {0};                     // aec_get_config_string()
};
Status status();
// Раз в N с, пока AEC считает: строка лога (и окно ослабления начинается заново)
void log_stat(const char *tag);

// Стенд «aec bench»: ~4 с синтетического эха (шум 300..3000 Гц, эхо с задержкой 12,5 мс), время на кадр, ослабление и сколько речи поверх эха сохраняется.
// Идёт в задаче AEC с повышенным приоритетом (чтобы вытеснение не искажало цифры), только когда динамик молчит. false: причина в why.
bool bench_start(char *why, size_t why_cap);
int bench_state();                          // 0 нет результата, 1 идёт, 2 готов
size_t bench_line(int i, char *buf, size_t cap);

// Команда «aec cal»: плата сама проигрывает 1,2 с шума, слушает его микрофоном и по корреляции измеряет задержку «запись в I2S -> эхо в микрофоне», потом
// ставит aec delay (и сохраняет). Нужна тишина в комнате и громкость динамика, как при музыке. Результат строками cal_line(). false: причина в why.
bool cal_start(char *why, size_t why_cap);
int cal_state();                            // 0 нет результата, 1 идёт, 2 готов
size_t cal_line(int i, char *buf, size_t cap);

}  // namespace aec
}  // namespace jarvis
