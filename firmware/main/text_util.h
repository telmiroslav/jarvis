#pragma once

// Мелкие помощники для текста (чистая логика, проверяется на обычном компьютере):
// проверка UTF-8, подгонка под набор символов шрифта и экранирование для JSON.

#include <stddef.h>
#include <stdint.h>

namespace jarvis {
namespace text {

// Какие символы есть в шрифтах интерфейса (main/fonts). Список зеркалит firmware/main/fonts/gen_fonts.sh:
// ASCII, русский алфавит с Ё/ё, « » № ° — … и ещё несколько типографских знаков, а с v0.6.0 ♪ (U+266A) и ⏸ (U+23F8) для строки музыки.
bool font_has_codepoint(uint32_t cp);

// Читает один символ UTF-8 из s (не дальше end). Возвращает длину символа в байтах (1..4)
// и кладёт код в *cp. Для битой последовательности возвращает 1 и *cp = 0xFFFD.
int utf8_decode(const char *s, const char *end, uint32_t *cp);

// Записывает код символа в dst (нужно место на 4 байта). Возвращает число записанных байт.
int utf8_encode(uint32_t cp, char *dst);

size_t utf8_count(const char *s);   // число символов (битый байт считается за один)

// Копирует src в dst (всего cap байт, включая нулевой). По дороге:
//   - битый UTF-8 и символы, которых нет в шрифте, заменяются на '?';
//   - '\n' остаётся (перенос строки), '\r' и '\t' превращаются в пробел, остальные управляющие выбрасываются;
//   - строка режется по границе символа, а не посреди него.
// Возвращает длину результата в байтах. src == nullptr даёт пустую строку.
size_t sanitize(const char *src, char *dst, size_t cap);

// Есть ли в тексте имя помощника: «Джарвис» (любой регистр, любое окончание: Джарвиса, ДЖАРВИСУ), «Жарвис» или Jarvis.
// Нужна, чтобы не дать голосом перебить ответ, в котором помощник сам произносит своё имя (динамик скажет слово, микрофон
// его услышит и плата перебила бы сама себя).
bool mentions_wake_name(const char *utf8);

// Экранирует s для JSON-строки в кавычках (кавычки сами не добавляет): ", \, управляющие.
// Возвращает длину результата; при нехватке места обрезает (всегда ставит нулевой байт).
size_t json_escape(const char *s, char *dst, size_t cap);

}  // namespace text
}  // namespace jarvis
