"""Служебные маркеры потока ИИ (llm.stream отдаёт текст (str) и эти два объекта). Отдельный модуль, чтобы addressing.py
(follow-молчание) мог их узнавать, не импортируя llm.py (тот сам импортирует addressing.py)."""
from __future__ import annotations


class _Marker:
    def __init__(self, name: str):
        self._name = name

    def __repr__(self) -> str:
        return self._name


# Перед вызовом функции: накопленный текст («Сейчас посмотрю») можно озвучивать, пока функция выполняется.
FLUSH = _Marker("FLUSH")

# Ответ ИИ оборвался и будет запрошен заново: всё, что отдано после последнего FLUSH и ещё не ушло плате (лежит в буфере предложений
# сессии), выбросить. Уже отправленные предложения остаются (см. llm.Commit).
RESET = _Marker("RESET")
