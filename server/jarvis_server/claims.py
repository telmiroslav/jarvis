"""Счётчик «вранья»: ИИ говорит о действии («Открываю YouTube», «Нажимаю»), хотя функцию в этом ходе не вызывал (или она не удалась).

Только для лога (поле claim= в строке TURN): ничего не повторяет и не исправляет. Эвристика по словам, ложные срабатывания возможны
на рассказах («Колумб открыл Америку»), поэтому счётчик включается лишь пока доступны функции управления ПК (session.py)."""
from __future__ import annotations

import re
from typing import Any, Iterable

# Глагол первого лица: настоящее («открываю»), прошедшее («открыл», «открыла») и будущее совершенного вида («открою»: «сейчас открою» без
# вызова функции тоже обещание, которого никто не выполнял). Слова целиком, ё как е. «Не могу открыть» (инфинитив) сюда не попадает.
_PRESENT = ("открываю включаю запускаю нажимаю жму ищу переключаю выключаю ставлю закрываю воспроизвожу перехожу перезагружаю "
            "блокирую прибавляю убавляю увеличиваю уменьшаю повышаю понижаю приглушаю отключаю останавливаю пускаю перематываю "
            "листаю пролистываю кликаю печатаю набираю отправляю сворачиваю разворачиваю перемещаю переношу меняю настраиваю "
            "устанавливаю выставляю регулирую выполняю").split()
_FUTURE = ("открою включу запущу нажму найду переключу выключу поставлю закрою воспроизведу перейду перезагружу заблокирую "
           "прибавлю убавлю увеличу уменьшу отключу остановлю пущу отправлю сделаю выполню").split()
_PAST_M = ("открыл включил запустил нажал нашел переключил выключил поставил закрыл воспроизвел перешел перезагрузил "
           "заблокировал прибавил убавил увеличил уменьшил повысил понизил приглушил отключил остановил пустил перемотал "
           "пролистал кликнул напечатал набрал отправил свернул развернул переместил перенес изменил настроил установил "
           "выставил отрегулировал сделал выполнил").split()
_IRREGULAR_F = {"нашел": "нашла", "перешел": "перешла", "перенес": "перенесла"}  # у остальных женский род = мужской + «а»
_PAST_F = [_IRREGULAR_F.get(w, w + "а") for w in _PAST_M]
ACTION_WORDS = frozenset(_PRESENT + _FUTURE + _PAST_M + _PAST_F)
_NEGATION = frozenset({"не", "ни"})
_WORD = re.compile(r"[a-zа-я]+")


def claims_action(text: str) -> bool:
    """В тексте есть глагол действия в первом лице (открываю, открыл, включаю...), перед которым нет «не»."""
    words = _WORD.findall((text or "").lower().replace("ё", "е"))
    return any(w in ACTION_WORDS and (i == 0 or words[i - 1] not in _NEGATION) for i, w in enumerate(words))


def call_ok(response: Any) -> bool:
    """Функция удалась: ok=true; у функций без поля ok (get_time) удачей считается ответ без поля error."""
    if not isinstance(response, dict):
        return False
    if "ok" in response:
        return response["ok"] is True
    return "error" not in response


def lied(text: str, tool_names: Iterable[str], calls: Iterable[Any]) -> bool:
    """claim=1: ИИ говорит о действии, а функции не вызвано вовсе (tool_names пусто) либо ни одна не вернула ok=true.
    calls: записи вызовов (memory.ToolCall); если их нет, а имена функций есть (подделки в тестах), считаем, что вызов был."""
    if not claims_action(text):
        return False
    names, recs = list(tool_names), list(calls)
    if not names:
        return True
    return bool(recs) and not any(call_ok(getattr(r, "response", None)) for r in recs)
