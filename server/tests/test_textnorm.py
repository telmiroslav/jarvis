@pytest.mark.parametrize("src,exp", [
    ("Джарвис, ты меня слышишь?", "Ты меня слышишь?"),
    ("Джарис, ты меня слышишь?", "Ты меня слышишь?"),
    ("жарвис включи свет", "Включи свет"),
    ("Jarvis, what time is it?", "What time is it?"),
    ("Джарвис, Джарвис, включи свет", "Включи свет"),
    ("кнопки привет джарвис можешь рассказать", "Привет джарвис можешь рассказать"),
])
def test_ptt_strips_only_leading_name_when_more_words_follow(src, exp):
    assert strip_wake_word(src, "ptt") == exp


@pytest.mark.parametrize("src,exp", [
    ("Джарвис", "Джарвис"),
    ("Джарвис?", "Джарвис?"),
    ("жарвис.", "жарвис."),
    ("Джарвис Джарвис", "Джарвис"),  # снимается одно обращение, пустым текст не станет
    ("Привет, Джарвис", "Привет, Джарвис"),
    ("привет Джарвис как дела", "привет Джарвис как дела"),
    ("Эй, Джарвис, включи свет", "Эй, Джарвис, включи свет"),
    ("Вис, включи свет", "Вис, включи свет"),  # хвост «вис» снимается только в режиме wake
    ("вис", "вис"),
    ("вис Джарвис", "вис Джарвис"),
])
def test_ptt_never_empties_and_keeps_greeting_and_fragments(src, exp):
    assert strip_wake_word(src, "ptt") == exp


def test_unknown_mode_behaves_like_ptt():
    assert strip_wake_word("Джарвис", "future") == "Джарвис"
    assert strip_wake_word("Джарвис, включи свет", "future") == "Включи свет"
    assert strip_wake_word("привет Джарвис", "") == "привет Джарвис"


def test_strip_keeps_case_of_proper_words_and_digits():
    assert strip_wake_word("Джарвис, iPhone разряжен", "wake") == "iPhone разряжен"
    assert strip_wake_word("Джарвис, 5 минут таймер", "wake") == "5 минут таймер"
    assert strip_wake_word("Джарвис, Москва далеко?", "wake") == "Москва далеко?"
    assert strip_wake_word("  Джарвис,   включи   свет ", "ptt") == "Включи свет"
    assert strip_wake_word("включи   свет ", "wake") == "включи свет"
